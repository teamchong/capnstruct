import type { FieldDesc, StructDefLike } from './index.js';

export interface RustCodegenOptions {
  /** Additional `#[derive(...)]` traits (default: `['Copy', 'Clone', 'Debug', 'PartialEq']`). */
  derive?: readonly string[];
  /** Emit compile-time size/align/offset_of assertions (default: `true`). */
  assertions?: boolean;
  /** Visibility modifier for structs and fields (default: `'pub'`). */
  vis?: 'pub' | 'pub(crate)' | '';
}

export interface GoCodegenOptions {
  /** Go package name (default: `'capnschema'`, or `'main'` when `wasm: true`). */
  pkg?: string;
  /** Emit compile-time size/align/offsetof assertions (default: `true`). */
  assertions?: boolean;
  /** Emit `//go:wasmexport capn_alloc` & `capn_reset` arena helpers for Go (`GOOS=wasip1 GOARCH=wasm`) and TinyGo (`-target=wasi`) WebAssembly (default: `false`). */
  wasm?: boolean;
}

export type SchemaCollection =
  | StructDefLike<any>
  | readonly StructDefLike<any>[]
  | Record<string, unknown>;

function collectDefs(input: SchemaCollection): StructDefLike[] {
  const seen = new Set<string>(),
    out: StructDefLike[] = [],
    visit = (d: any, name = d?.name || 'AnonStruct'): void => {
      if (d?.kind === 'struct') {
        if (!seen.has(name)) {
          seen.add(name);
          for (const f of d.fieldList) visit(f.desc);
          out.push({ ...d, name, rustType: name });
        }
      } else if (d?.element) visit(d.element);
    };
  if ((input as any)?.kind === 'struct') visit(input, (input as any).name || 'Root');
  else for (const [k, v] of Object.entries(input)) visit(v, (v as any)?.name || (Array.isArray(input) ? 'Struct' + k : k));
  return out;
}

const hasFloat = (d: any, s = new Set()): boolean =>
  !s.has(d) &&
  !!s.add(d) &&
  !!(d.float || (d.element && hasFloat(d.element, s)) || d.fieldList?.some((f: any) => hasFloat(f.desc, s)));

const HDR = '// Auto-generated by capnstruct. DO NOT EDIT.\n';

const fmtBody = (def: StructDefLike, fmtF: (f: any) => string, fmtP: (p: string, n: number) => string) => {
  let cur = 0,
    pad = 0,
    out: string[] = [];
  for (const f of def.fieldList) {
    if (f.offset > cur) out.push(fmtP('_pad' + pad++, f.offset - cur));
    out.push(fmtF(f));
    cur = f.offset + f.size;
  }
  if (def.size > cur) out.push(fmtP('_pad' + pad, def.size - cur));
  return out.join('\n');
};

export function toRustReprC(schemas: SchemaCollection, opts: RustCodegenOptions = {}): string {
  const defs = collectDefs(schemas),
    drv0 = opts.derive ?? ['Copy', 'Clone', 'Debug', 'PartialEq'],
    drvEq = opts.derive ? drv0 : [...drv0, 'Eq'],
    v = opts.vis === '' ? '' : (opts.vis ?? 'pub') + ' ',
    drv = (d: readonly string[]) => (d.length ? `#[derive(${d.join(', ')})]\n` : ''),
    eDrv = drv(drvEq),
    hdr = (t: string, f = 'len', m = '') =>
      `#[repr(C)]\n${eDrv}${v}struct ${t} {\n  ${v}off: u32,\n  ${v}${f}: u32,${m}\n}`,
    mk = `\n  ${v}_marker: core::marker::PhantomData<T>,`,
    blocks = [
      `${HDR}#![allow(dead_code, non_camel_case_types, non_snake_case)]\n\nfn _cs<T>(b: &[u8], o: usize, n: usize) -> &[T] {\n  if n == 0 { return &[]; }\n  let s = &b[o..o.checked_add(n.checked_mul(core::mem::size_of::<T>()).unwrap()).unwrap()];\n  unsafe { core::slice::from_raw_parts(s.as_ptr() as *const T, n) }\n}\n\n${hdr('CapnStr')}\nimpl CapnStr {\n  ${v}fn as_bytes<'a>(&self, b: &'a [u8]) -> &'a [u8] { _cs(b, self.off as usize, self.len as usize) }\n  ${v}fn as_str<'a>(&self, b: &'a [u8]) -> Result<&'a str, core::str::Utf8Error> { core::str::from_utf8(self.as_bytes(b)) }\n}\n\n${hdr('CapnSlice<T>', 'len', mk)}\nimpl<T> CapnSlice<T> {\n  ${v}fn as_slice<'a>(&self, b: &'a [u8]) -> &'a [T] { _cs(b, self.off as usize, self.len as usize) }\n}\n\n${hdr('CapnRef<T>', 'present', mk)}\nimpl<T> CapnRef<T> {\n  ${v}fn as_ref<'a>(&self, b: &'a [u8]) -> Option<&'a T> {\n    if self.present == 0 { None } else { _cs(b, self.off as usize, 1).first() }\n  }\n}`,
    ];
  for (const def of defs) {
    const n = def.name,
      u = (e: string, s: number) => `  assert!(core::mem::${e} == ${s});`,
      body = fmtBody(
        def,
        (f) => `  ${v}${f.name}: ${f.desc.rustType},`,
        (p, s) => `  ${v}${p}: [u8; ${s}],`,
      ),
      a =
        (opts.assertions ?? true)
          ? `\nconst _: () = {\n${u(`size_of::<${n}>()`, def.size)}\n${u(`align_of::<${n}>()`, def.align)}\n${def.fieldList.map((f) => u(`offset_of!(${n}, ${f.name})`, f.offset)).join('\n')}\n};`
          : '';
    blocks.push(
      `#[repr(C)]\n${drv(hasFloat(def) ? drv0 : drvEq)}${v}struct ${n} {\n${body}\n}\nimpl ${n} {\n  ${v}fn as_slice(base: &[u8], len: usize) -> &[Self] { _cs(base, 0, len) }\n}${a}`,
    );
  }
  return blocks.join('\n\n') + '\n';
}

export const generateRust = toRustReprC;

const goType = (d: any): string => {
  if (d.kind === 'primitive') {
    const t = d.type;
    return t > 'fixed' && t < 'fo'
      ? `[${d.length}]byte`
      : t === 'bool'
        ? 'uint8'
        : t === 'f16'
          ? 'uint16'
          : (t[0] === 'f' ? 'float' : t[0] === 'u' ? 'uint' : 'int') + t.slice(1);
  }
  return d.kind === 'str'
    ? 'CapnStr'
    : d.kind === 'struct'
      ? d.name || 'AnonStruct'
      : d.kind === 'array'
        ? `[${d.length}]${goType(d.element)}`
        : `Capn${d.kind === 'ref' ? 'Ref' : 'Slice'}[${goType(d.element)}]`;
};

const goField = (s: string) => s[0].toUpperCase() + s.slice(1);

export function toGoStruct(schemas: SchemaCollection, opts: GoCodegenOptions = {}): string {
  const defs = collectDefs(schemas),
    wasm = opts.wasm ?? false,
    blocks = [
      `${HDR}package ${opts.pkg || (wasm ? 'main' : 'capnschema')}\n\nimport "unsafe"`,
      ...(wasm
        ? [
            `var _capnB CapnBuilder\n//go:wasmexport capn_alloc\nfunc CapnAlloc(n uint32) uintptr {\n\tif n == 0 { return 0 }\n\treturn uintptr(unsafe.Pointer(&_capnB.Buf[_capnB.alloc(int(n), 8)]))\n}\n//go:wasmexport capn_reset\nfunc CapnReset() { _capnB.Reset() }`,
          ]
        : []),
      `func CapnBytes(ptr uintptr, byteLen uint32) []byte {\n\tif ptr == 0 || byteLen == 0 { return nil }\n\treturn unsafe.Slice((*byte)(unsafe.Pointer(ptr)), byteLen)\n}\nfunc CapnView[T any](b []byte) *T { return &CapnSliceView[T](b, 1)[0] }\nfunc CapnSliceView[T any](b []byte, n uint32) []T {\n\tif n == 0 { return nil }\n\tvar z T\n\tif uint64(n)*uint64(unsafe.Sizeof(z)) > uint64(len(b)) { panic("oob") }\n\treturn unsafe.Slice((*T)(unsafe.Pointer(unsafe.SliceData(b))), n)\n}\ntype CapnStr struct{ Off, Len uint32 }\nfunc (s CapnStr) Bytes(b []byte) []byte { return CapnSliceView[byte](b[s.Off:], s.Len) }\nfunc (s CapnStr) String(b []byte) string { return unsafe.String(unsafe.SliceData(s.Bytes(b)), s.Len) }\ntype CapnSlice[T any] struct{ Off, Len uint32 }\nfunc (s CapnSlice[T]) Slice(b []byte) []T { return CapnSliceView[T](b[s.Off:], s.Len) }\ntype CapnRef[T any] struct{ Off, Present uint32 }\nfunc (r CapnRef[T]) Ptr(b []byte) *T {\n\tif r.Present == 0 { return nil }\n\treturn CapnView[T](b[r.Off:])\n}\ntype CapnBuilder struct {\n\tBuf []byte\n\tdedup map[string]CapnStr\n}\nfunc (b *CapnBuilder) Reset(buf ...[]byte) {\n\tif len(buf) > 0 { b.Buf = buf[0] }\n\tb.Buf = b.Buf[:0]\n\tclear(b.dedup)\n}\nfunc (b *CapnBuilder) alloc(n, a int) int {\n\tp := len(b.Buf)\n\to := (p + a - 1) &^ (a - 1)\n\te := o + n\n\tif e > cap(b.Buf) { b.Buf = append(b.Buf, make([]byte, e-p)...) }\n\tb.Buf = b.Buf[:e]\n\tclear(b.Buf[p:e])\n\treturn o\n}\nfunc (b *CapnBuilder) Str(s string) CapnStr {\n\treturn CapnStr(CapnPackSlice(b, unsafe.Slice(unsafe.StringData(s), len(s))))\n}\nfunc (b *CapnBuilder) StrDedup(s string) CapnStr {\n\tif c, ok := b.dedup[s]; ok || s == "" { return c }\n\tif b.dedup == nil { b.dedup = map[string]CapnStr{} }\n\tb.dedup[s] = b.Str(s)\n\treturn b.dedup[s]\n}\nfunc (b *CapnBuilder) Bytes() []byte { return b.Buf }\nfunc CapnBuildSlice[T any](b *CapnBuilder, n int, fn func(int, *CapnBuilder) T) CapnSlice[T] {\n\tif n <= 0 { return CapnSlice[T]{} }\n\tvar z T\n\to := b.alloc(n*int(unsafe.Sizeof(z)), int(unsafe.Alignof(z)))\n\tfor i := 0; i < n; i++ {\n\t\tv := fn(i, b)\n\t\tCapnSliceView[T](b.Buf[o:], uint32(n))[i] = v\n\t}\n\treturn CapnSlice[T]{uint32(o), uint32(n)}\n}\nfunc CapnBuild[T any](b *CapnBuilder, fn func(*CapnBuilder) T) []byte {\n\tb.Reset()\n\tCapnBuildSlice(b, 1, func(_ int, b *CapnBuilder) T { return fn(b) })\n\treturn b.Buf\n}\nfunc CapnPackSlice[T any](b *CapnBuilder, s []T) CapnSlice[T] {\n\treturn CapnBuildSlice(b, len(s), func(i int, _ *CapnBuilder) T { return s[i] })\n}\nfunc CapnPack[T any](b *CapnBuilder, s []T) []byte {\n\tb.Reset()\n\tCapnPackSlice(b, s)\n\treturn b.Buf\n}\nfunc CapnPackRef[T any](b *CapnBuilder, v *T) CapnRef[T] {\n\tif v == nil { return CapnRef[T]{} }\n\treturn CapnRef[T]{CapnPackSlice(b, unsafe.Slice(v, 1)).Off, 1}\n}`,
    ];
  for (const def of defs) {
    const n = def.name,
      u = (e: string, s: number) => `\t_ = [1]int{}[unsafe.${e}-${s}]`,
      body = fmtBody(
        def,
        (f) => `\t${goField(f.name)} ${goType(f.desc)}`,
        (p, s) => `\t${p} [${s}]byte`,
      ),
      a =
        (opts.assertions ?? true)
          ? `\nvar (\n${u(`Sizeof(${n}{})`, def.size)}\n${u(`Alignof(${n}{})`, def.align)}\n${def.fieldList.map((f) => u(`Offsetof(${n}{}.${goField(f.name)})`, f.offset)).join('\n')}\n)`
          : '';
    blocks.push(`type ${n} struct {\n${body}\n}${a}`);
  }
  return blocks.join('\n\n') + '\n';
}

export const generateGo = toGoStruct;
