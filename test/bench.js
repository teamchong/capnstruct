// ---------------------------------------------------------------------------
// 6. Cyclic Graph Traversal & Clone (10,000 Doubly-Linked Ring Nodes)
// ---------------------------------------------------------------------------
const N_RING = 10_000;
const RING_CLUSTER = 50; // 200 cyclic rings of 50 nodes (V8 structuredClone overflows C++ call stack above ~1,000 hop depth; capnstruct packs any depth in O(1) stack)
const jsRing = Array.from({ length: N_RING }, (_, i) => ({
  id: i,
  weight: i * 1.25,
  next: null,
  prev: null,
}));
for (let i = 0; i < N_RING; i++) {
  const base = Math.floor(i / RING_CLUSTER) * RING_CLUSTER;
  const off = i % RING_CLUSTER;
  jsRing[i].next = jsRing[base + ((off + 1) % RING_CLUSTER)];
  jsRing[i].prev = jsRing[base + ((off + RING_CLUSTER - 1) % RING_CLUSTER)];
}
const capnRingBytes = RingNode.pack(jsRing);
const ringWasmOff = (arenaView.byteOffset + arenaView.byteLength + 7) & ~7;
new Uint8Array(rustMem.buffer, ringWasmOff, capnRingBytes.byteLength).set(capnRingBytes);
const goRingPtr = goExports.capn_alloc(capnRingBytes.byteLength);
new Uint8Array(goExports.memory.buffer, goRingPtr, capnRingBytes.byteLength).set(capnRingBytes);
const tinyRingPtr = tinyExports ? tinyExports.capn_alloc(capnRingBytes.byteLength) : 0;
if (tinyExports) {
  new Uint8Array(tinyExports.memory.buffer, tinyRingPtr, capnRingBytes.byteLength).set(capnRingBytes);
}
console.log(
  `\n6) Cyclic Graph Clone & Traversal (${N_RING.toLocaleString()} Doubly-Linked Ring Nodes - JSON/serde_json throws TypeError!):`,
);

const b6CloneRing = bench(
  'JS structuredClone(cyclicRing) + traverse',
  20,
  () => {
    const cloned = structuredClone(jsRing);
    let sum = 0;
    for (let c = 0; c < N_RING; c += RING_CLUSTER) {
      let cur = cloned[c];
      for (let j = 0; j < RING_CLUSTER; j++) {
        sum += cur.weight;
        cur = cur.next;
      }
    }
    return sum;
  },
  () => structuredClone(jsRing),
);

const b6CapnRing = bench(
  'JS capnstruct ref(() => RingNode) (0 MB)',
  20,
  () => {
    const view = RingNode.array(capnRingBytes);
    let sum = 0;
    for (let c = 0; c < N_RING; c += RING_CLUSTER) {
      let cur = view.cursor(c);
      for (let j = 0; j < RING_CLUSTER; j++) {
        sum += cur.weight;
        cur = cur.next;
      }
    }
    return sum;
  },
  () => RingNode.array(capnRingBytes),
);

