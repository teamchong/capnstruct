function instantiateWasiKernel(wasmBytes) {
  let inst;
  const shim = {
    wasi_snapshot_preview1: new Proxy(
      {},
      {
        get: (_, k) => {
          if (k === 'args_sizes_get' || k === 'environ_sizes_get') {
            return (cPtr, bPtr) => {
              const dv = new DataView(inst.exports.memory.buffer);
              dv.setUint32(cPtr, 0, true);
              dv.setUint32(bPtr, 0, true);
              return 0;
            };
          }
          if (k === 'clock_time_get') {
            return (_id, _prec, tPtr) => {
              const dv = new DataView(inst.exports.memory.buffer);
              dv.setBigUint64(tPtr, BigInt(Date.now()) * 1000000n, true);
              return 0;
            };
          }
          if (k === 'random_get') {
            return (p, l) => {
              new Uint8Array(inst.exports.memory.buffer, p, l).fill(1);
              return 0;
            };
          }
          if (k === 'fd_write') {
            return (_fd, iovsPtr, iovsLen, nwrittenPtr) => {
              const dv = new DataView(inst.exports.memory.buffer);
              let total = 0;
              for (let i = 0; i < iovsLen; i++) total += dv.getUint32(iovsPtr + i * 8 + 4, true);
              dv.setUint32(nwrittenPtr, total, true);
              return 0;
            };
          }
          return () => 0;
        },
      },
    ),
  };
  inst = new WebAssembly.Instance(new WebAssembly.Module(wasmBytes), shim);
  inst.exports._initialize();
  return inst.exports;
}

